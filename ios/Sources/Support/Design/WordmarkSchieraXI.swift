import SwiftUI

/// Il nome «SchieraXI» disegnato (variante «Tribuna», dai tracciati del sito): «Schiera» nel colore del testo, «XI» nel colore
/// d'accento (`Color.xi`). Sono forme, non un carattere: nessun font da includere, si adatta a qualsiasi altezza.
/// Con `puntino` la «I» ha il taglio obliquo che stacca il punto in testa (per le misure grandi: sotto i 30 punti non si vedrebbe).
/// Le coordinate di `NomeForma` vengono da uno script (non ritoccarle a mano): rifarle dagli SVG se il disegno cambia.
/// Per VoiceOver il nome si legge «Schiera undici»: dove c'è già il marchio con la stessa etichetta, nasconderlo con `.accessibilityHidden(true)`.
struct WordmarkSchieraXI: View {
    /// Larghezza diviso altezza del disegno.
    static let rapporto: CGFloat = 4.7339
    var puntino = false

    var body: some View {
        ZStack {
            NomeForma().fill(.primary)
            XIForma(puntino: puntino).fill(Color.xi)
        }
        .aspectRatio(Self.rapporto, contentMode: .fit)
        .accessibilityElement()
        .accessibilityLabel("Schiera undici")
    }
}

/// Lo slogan sotto il nome: «Schierali. Schiera gli XI.», con «XI» nel colore d'accento.
struct SloganSchieraXI: View {
    var body: some View {
        Text("Schierali. Schiera gli \(Text("XI").foregroundStyle(Color.xi).fontWeight(.heavy)).")
            .accessibilityLabel("Schierali. Schiera gli undici")
    }
}

/// Il nome grande delle schermate di ingresso (accesso, primo avvio): segue la dimensione del testo, con un tetto.
/// Nascosto a VoiceOver: accanto c'è il marchio, che dice già il nome.
struct NomeSchieraXIGrande: View {
    @ScaledMetric(relativeTo: .largeTitle) private var altezza: CGFloat = 30
    var body: some View {
        WordmarkSchieraXI(puntino: true)
            .frame(height: min(altezza, 60))
            .accessibilityHidden(true)
    }
}

private func scala(_ r: CGRect) -> (CGFloat, CGFloat) -> CGPoint {
    let s = min(r.width / 3675.4, r.height / 776.4)
    return { x, y in CGPoint(x: r.minX + x * s, y: r.minY + y * s) }
}

