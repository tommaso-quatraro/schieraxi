const LINGUE = { it: "Italiano", en: "English" };
const ETA_MINIMA = 14;                      // come in fanta/testi_legali.py

const memLeggi = k => { try { return localStorage.getItem(k); } catch { return null; } };
const memScrivi = (k, v) => { try { localStorage.setItem(k, v); } catch { /* niente memoria: vale solo adesso */ } };
function linguaIniziale() {
  const scelta = memLeggi("lingua");
  if (scelta && Object.hasOwn(LINGUE, scelta)) return scelta;
  const nav = typeof navigator !== "undefined" ? ((navigator.languages && navigator.languages[0]) || navigator.language || "") : "";
  return /^en(\b|-|_)/i.test(nav) ? "en" : "it";            // prima visita: la lingua del browser (italiano se non è inglese)
}
let LINGUA = linguaIniziale();

function t(chiave, valori) {
  const testo = (TESTI[LINGUA] && TESTI[LINGUA][chiave]) ?? TESTI.it[chiave];
  if (testo === undefined) return chiave;              // chiave mancante: si vede subito in giro
  return valori ? testo.replace(/\{(\w+)\}/g, (m, k) => (k in valori ? String(valori[k]) : m)) : testo;
}
// Plurali: tp(chiave, n) usa «chiave.one» o «chiave.other» secondo la lingua (con {n} = numero).
function tp(chiave, n, valori) {
  const categoria = new Intl.PluralRules(t("lingua.locale")).select(n);
  return t(Object.hasOwn(TESTI.it, `${chiave}.${categoria}`) ? `${chiave}.${categoria}` : `${chiave}.other`, { n, ...valori });
}

// Formati con la lingua scelta (date, ore, numeri).
const fData = (d, opz = { day: "numeric", month: "short" }) => d.toLocaleDateString(t("lingua.locale"), opz);
const fOra = d => d.toLocaleTimeString(t("lingua.locale"), { hour: "2-digit", minute: "2-digit" });
const fDataOra = d => d.toLocaleString(t("lingua.locale"), { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" });
const fNum = (n, opz) => Number(n).toLocaleString(t("lingua.locale"), opz);

// Tempi scritti dal server («3 ore fa», «meno di un'ora», «circa 2 ore») nella lingua scelta.
const UNITA_EN = { minuto: ["minute", "minutes"], minuti: ["minute", "minutes"], ora: ["hour", "hours"], ore: ["hour", "hours"], giorno: ["day", "days"], giorni: ["day", "days"] };
function traduciDurata(v) {
  if (LINGUA === "it" || typeof v !== "string") return v;
  return v.replace(/meno di un minuto fa/, "less than a minute ago").replace(/meno di un'ora/, "less than an hour")
    .replace(/(circa )?(\d+) (minuto|minuti|ora|ore|giorno|giorni)\b( fa)?/g, (m, circa, n, u, fa) => `${circa ? "about " : ""}${n} ${UNITA_EN[u][Number(n) === 1 ? 0 : 1]}${fa ? " ago" : ""}`);
}

// Messaggi del server: restano in italiano nelle risposte (li leggono anche iOS e Android); qui, se la lingua non è l'italiano,
// si riconoscono dalle chiavi «err.*» (il testo italiano della chiave è il messaggio del server, {1}, {2}... sono le parti variabili).
let regoleErrori = null;
function traduciErrore(messaggio) {
  if (LINGUA === "it" || typeof messaggio !== "string") return messaggio;
  if (!regoleErrori) {
    regoleErrori = Object.keys(TESTI.it).filter(k => k.startsWith("err.") || k.startsWith("srv.")).map(k =>
      [k, new RegExp("^" + TESTI.it[k].replace(/[.*+?^$()|[\]\\]/g, "\\$&").replace(/\{(\w+)\}/g, "(.+?)") + "$")]);
  }
  for (const [k, re] of regoleErrori) {
    const m = messaggio.match(re);
    if (m) return t(k, Object.fromEntries(m.slice(1).map((v, i) => [String(i + 1), traduciDurata(v)])));
  }
  return messaggio;
}

// Scelta della lingua: ricordata su questo dispositivo e, con un account, per quell'utente (così ogni utente trova la sua).
function scegliLingua(lingua, utente) {
  if (!Object.hasOwn(LINGUE, lingua)) return;
  memScrivi("lingua", lingua);
  if (utente) memScrivi(`lingua:${utente}`, lingua);
  location.reload();
}
// Dopo l'accesso: se questo utente aveva scelto un'altra lingua si ricarica con la sua (true = sto ricaricando); se non l'aveva scelta, si ricorda quella di adesso.
function usaLinguaDi(utente) {
  if (!utente) return false;
  const mia = memLeggi(`lingua:${utente}`);
  if (!mia || !Object.hasOwn(LINGUE, mia)) { memScrivi(`lingua:${utente}`, LINGUA); return false; }
  if (mia === LINGUA) return false;
  memScrivi("lingua", mia);
  location.reload();
  return true;
}

