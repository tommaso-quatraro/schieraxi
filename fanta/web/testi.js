// Tempi scritti dal server («3 ore fa», «meno di un'ora», «circa 2 ore») nella lingua scelta.
const UNITA_EN = { minuto: ["minute", "minutes"], minuti: ["minute", "minutes"], ora: ["hour", "hours"], ore: ["hour", "hours"], giorno: ["day", "days"], giorni: ["day", "days"] };
function traduciDurata(v) {
  if (LINGUA === "it" || typeof v !== "string") return v;
  return v.replace(/meno di un minuto fa/, "less than a minute ago").replace(/meno di un'ora/, "less than an hour")
    .replace(/(circa )?(\d+) (minuto|minuti|ora|ore|giorno|giorni)\b( fa)?/g, (m, circa, n, u, fa) => `${circa ? "about " : ""}${n} ${UNITA_EN[u][Number(n) === 1 ? 0 : 1]}${fa ? " ago" : ""}`);
}

// Messaggi del server: restano in italiano nelle risposte (li leggono anche iOS e Android); qui, se la lingua non è l'italiano,
// si riconoscono dalle chiavi «err.*» (il testo italiano della chiave è il messaggio del server, {1}, {2}... sono le parti variabili).
let regoleErrori = null;
function traduciErrore(messaggio) {
  if (LINGUA === "it" || typeof messaggio !== "string") return messaggio;
  if (!regoleErrori) {
    // dal più specifico (più testo fisso) al più generico: «Squadra non trovata: {1}» non deve rubare un messaggio più lungo
    regoleErrori = Object.keys(TESTI.it).filter(k => k.startsWith("err.") || k.startsWith("srv.")).map(k =>
      [k, new RegExp("^" + TESTI.it[k].replace(/[.*+?^$()|[\]\\]/g, "\\$&").replace(/\{(\w+)\}/g, "(.+?)") + "$"), TESTI.it[k].replace(/\{\w+\}/g, "").length])
      .sort((a, b) => b[2] - a[2]);
  }
  for (const [k, re] of regoleErrori) {
    const m = messaggio.match(re);
    if (m) return t(k, Object.fromEntries(m.slice(1).map((v, i) => [String(i + 1), traduciParametro(v)])));
  }
  return messaggio;
}
// Una parte variabile di un messaggio: un tempo («3 ore fa»), un nome che il server scrive in italiano («ricerche di scambi», «dare») o un
// altro messaggio intero (chiavi «err.p_*»); altrimenti resta com'è (nomi di squadre, numeri).
let paroleErrori = null;
function traduciParametro(v) {
  if (!paroleErrori) paroleErrori = new Map(Object.keys(TESTI.it).filter(k => k.startsWith("err.p_")).map(k => [TESTI.it[k], k]));
  return paroleErrori.has(v) ? t(paroleErrori.get(v)) : traduciGiornata(v) ?? traduciDurata(v);
}
// La giornata dentro un messaggio del server, con il suo articolo («la Giornata 8 · 11ª di Serie A», «l'11ª giornata di Serie A»:
// frasi.nome_giornata sul server): nella lingua scelta e senza l'articolo italiano. null se il testo non è una giornata.
let regoleGiornata = null;
function traduciGiornata(v) {
  if (!regoleGiornata) regoleGiornata = ["frase.giornata.lega", "frase.giornata.serie_a"].map(k => [k, new RegExp("^(?:la |l')?"
    + TESTI.it[k].replace(/[.*+?^$()|[\]\\]/g, "\\$&").replace(/\{(\w+)\}/g, "(?<$1>\\d+)") + "$")]);
  for (const [k, re] of regoleGiornata) { const m = re.exec(v); if (m) return t(k, m.groups); }
  return null;
}

// Frasi del server con la chiave (fanta/frasi.py): {chiave, param} accanto al testo italiano. In italiano si mostra il testo del server
// (è già giusto); nelle altre lingue si traduce da «frase.<chiave>», con i parametri nella lingua scelta (i decimali arrivano già come testo «1.5», le frasi dentro
// le frasi si traducono a loro volta). Senza chiave, o con una chiave che questa versione non conosce, si prova a riconoscere il testo italiano come per gli errori.
function testoParametro(v) {
  if (v && typeof v === "object" && !Array.isArray(v)) return traduciFrase(v, "");
  if (Array.isArray(v)) return v.map(testoParametro).join(", ");
  // un numero negativo con il meno tipografico («−0.6», mai «-0.6»), come `segno` e il testo italiano del server (#392)
  if (typeof v === "number" && v < 0) return "−" + String(-v);
  if (typeof v === "string" && /^-\d+(\.\d+)?$/.test(v)) return "−" + v.slice(1);
  if (typeof v === "string") return v.split("; ").map(traduciErrore).join("; ");           // un testo salvato prima di avere la chiave (nomi, squadre: non cambiano)
  return v;
}
function traduciFrase(frase, italiano) {
  if (LINGUA === "it") return italiano ?? "";
  if (!frase || typeof frase.chiave !== "string") return traduciErrore(italiano);
  const p = frase.param || {};
  if (frase.chiave === "elenco" || frase.chiave === "elenco_e") {
    const parti = (p.parti || []).map(testoParametro), sep = p.sep ?? ", ";
    return frase.chiave === "elenco_e" && parti.length > 1 ? parti.slice(0, -1).join(sep) + t("frase.elenco.e") + parti[parti.length - 1] : parti.join(sep);
  }
  const base = "frase." + frase.chiave;
  const plurale = Object.hasOwn(TESTI.it, base + ".other");
  const chiave = plurale ? base + (new Intl.PluralRules(t("lingua.locale")).select(Number(p.n)) === "one" ? ".one" : ".other") : base;
  if (!Object.hasOwn(TESTI[LINGUA] || {}, chiave)) return traduciErrore(italiano);
  return t(chiave, Object.fromEntries(Object.entries(p).map(([k, v]) => [k, testoParametro(v)]))).replace(/\.\.$/, ".");
}
// Come sopra per un oggetto che ha il testo e la sua frase: {testo, frase}, {perche, perche_frase}...
const testoDi = (oggetto, campo = "testo", frase = campo === "testo" ? "frase" : campo + "_frase") => traduciFrase(oggetto && oggetto[frase], oggetto && oggetto[campo]);
// Un elenco di testi con l'elenco parallelo delle frasi: {motivi: [...], motivi_frasi: [...]}
const testiDi = (oggetto, campo, frasi = campo + "_frasi") => ((oggetto && oggetto[campo]) || []).map((x, i) => traduciFrase(oggetto[frasi] && oggetto[frasi][i], x));

